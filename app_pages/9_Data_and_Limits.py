"""Data & Limits: sources, pipeline, validation results (from src/validate.py) and the full list of limits."""
import json

import pandas as pd
import streamlit as st

from src import data, indicators, limits, ui
from src.sources import registry

fed = data.table("federations")
validation = data.table("validation")
report = json.loads((data.PROCESSED / "build_report.json").read_text())
rates = indicators.departement_rates(data.table("lic_dep_fed"), data.table("population_dep"),
                                     indicators.territory_codes(fed))

st.title("Data & Limits")

st.header("Sources")
sources = pd.DataFrame(registry.SOURCES, columns=registry.COLUMNS)
st.dataframe(sources, hide_index=True, width="stretch",
             column_config={"Link": st.column_config.LinkColumn("Link", display_text="open")})
st.caption("S = Sources Principales, R = Données de Références,  G = Géographie, V = Références de Validation, Q = Chiffres Cités(Quoted) ,Licence Ouverte = Etalab Open Licence. Raw files are downloaded by `python -m src.build`; the app reads "
           "only the processed tables.")

st.header("Pipeline")
n_communes = len(data.table("population_com"))
st.markdown(
    f"""
1. **Download** — `src/build.py` fetches every raw file once ({len(registry.SOURCES)} datasets, table above) into
   `data/raw/` (not shipped).
2. **Read and type** — `src/sources/`: codes kept as text ("01", "2A", "01053"), counts as integers; derived
   counts per row (women, men, 60+, QPV residents).
3. **Harmonise geography** — `src/geo.py`: Paris/Lyon/Marseille districts → city; {report['merged_commune_codes_mapped']}
   communes merged since 2024 → current commune (INSEE COG 2026); {ui.fmt_num(n_communes)} communes joined to their
   2023 population.
4. **Aggregate** — compact tables by département × federation, commune × federation and federation × sex × age
   (`data/processed/`, parquet), simplified outlines ({report['departement_features']} mainland départements,
   {report['overseas_features']} overseas, {ui.fmt_num(report['commune_features'])} communes).
5. **Validate** — `src/validate.py` checks totals against INJEP's published figures, internal sums and join
   rates (results below; also run by `pytest`).
"""
)

st.header("Validation")
passed = int(validation["passed"].sum())
st.metric("Checks passed", f"{passed} / {len(validation)}",
          help="Generated by `python -m src.validate` (saved to data/processed/validation.parquet).")
st.dataframe(validation, hide_index=True, width="stretch",
             column_config={"group": "Group", "check": "Check", "observed": "Observed", "expected": "Expected",
                            "passed": st.column_config.CheckboxColumn("Passed"), "note": "Note"})
ui.source_caption("INJEP published results 2023 (July 2024) and 2024 (July 2025, revised 2023 history); INSEE.")

st.header("Limits")
for topic, text in limits.limits(fed, rates, validation):
    st.markdown(f"- **{topic}.** {text}")
st.caption("Detailed audit of every source: docs/data_audit.md.")
